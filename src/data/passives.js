/** Подпись узла: «Урон атаки (Attack Damage) +4/очко». */
export function nodeLabel(node) {
  const meta = PASSIVE_STATS[node[0]] || { ru: node[0], en: node[0], pct: false };
  const unit = meta.pct ? '%' : '';
  return `${meta.ru} (${meta.en}) +${node[1]}${unit}/очко`;
}

/** Короткая подпись значения: «+4% за очко, до 3 очков». */
export function nodeValueLabel(node) {
  const meta = PASSIVE_STATS[node[0]] || { pct: false };
  const unit = meta.pct ? '%' : '';
  return `+${node[1]}${unit} ×${node[2]}`;
}
