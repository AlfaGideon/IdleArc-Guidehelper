import { el, card, table } from './dom.js';
import { CHECKLIST } from '../data/builds.js';
import { DATA_META } from '../data/systems.js';

export function render(root) {
  root.innerHTML = '';
  root.appendChild(card('Как пользоваться приложением', [
    el('ol', {}, [
      el('li', { text: 'Планировщик: выберите класс, уровень и цель — приложение распределит классовые очки с учётом тиров и покажет приоритет статов, гемы, Drop Bonuses и талисманы.' }),
      el('li', { text: 'Калькуляторы: проверьте, что даёт конкретный крит/DD/DH-билд или Retaliation, посчитайте гем и Mastery.' }),
      el('li', { text: 'Кодекс: точечные цифры официальных источников (аффиксы, Drop Bonuses, гемы, петы, талисманы, гильдия, ML-анлоки).' }),
      el('li', { text: 'Перед тратами (рубины, Arcstone, шарды, гильд-сброс) сверяйтесь с разделом «Нюансы» — там ловушки билдостроения.' }),
    ]),
  ]));

  root.appendChild(card('Нюансы, которые чаще всего ломают билд', [
    el('div', { class: 'grid cols-2' }, CHECKLIST.map((c) =>
      el('div', { class: 'infobox' }, [el('b', { text: c.title }), el('p', { text: c.text })]))),
  ]));

  root.appendChild(card('Данные и источники', [
    el('p', { text: `Версия игры: ${DATA_META.gameVersion} · Патч вышел ${DATA_META.patchDate}. ${DATA_META.verified}.` }),
    table(['Источник', 'Ссылка'], DATA_META.sources.map((s) => [s.label, el('a', { href: s.url, target: '_blank', rel: 'noopener', text: s.url })])),
    el('div', { class: 'warnbox', style: 'margin-top:10px' }, [
      el('b', { text: 'Что подтверждено, а что — оценка' }),
      el('ul', { class: 'tight' }, [
        el('li', { text: 'Подтверждено официально: правила очков и тиров, названия и значения большинства классовых навыков (сайт игры + вики), аффиксы, Drop Bonuses, гемы, петы, талисманы, Mastery, ML-анлоки, Convergence, гильд-дерево, изменения 1.3.1.' }),
        el('li', { text: 'Требует проверки в игре: эффекты навыков Druid (официально опубликованы только названия), новый Warrior-навык Counterstrike (заменил Victory Rush), точные проценты Defense от навыков Warrior после реворка.' }),
        el('li', { text: 'Расчёты урона — модель на основе официальных правил (крит>100%, «полные сотни» DH/DD, DR-капы). Порядок слоёв урона в игре официально не раскрыт: используйте как сравнение вариантов, а не как точный DPS.' }),
        el('li', { text: 'Названия в интерфейсе игры — английские, поэтому приложение дублирует их: русская подпись + оригинальное название.' }),
      ]),
    ]),
    el('p', { class: 'muted', text: 'Игра обновляется очень часто (несколько балансных патчей в неделю). Если видите расхождение — сверяйтесь с патч-нотами и обновите снапшот данных в src/data/*.js.' }),
  ]));

  root.appendChild(card('Дисклеймер', [
    el('p', { text: 'Это неофициальный фанатский помощник. Он не связан с разработчиком IdleArc, не подключается к аккаунту игры, не автоматизирует геймплей и не требует логина. Все данные — публичные материалы официального сайта игры и открытой вики с указанием источников.' }),
  ]));
}
